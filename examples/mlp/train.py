#!/usr/bin/env python3
"""Fit the example's procedural RGB function; NumPy is a development-only dependency."""

import argparse
from pathlib import Path

import numpy as np


WIDTHS = (2, 32, 32, 3)


def reference(points):
    x = points[:, 0]
    y = points[:, 1]
    return np.stack((0.5 + 0.4 * np.sin(2.4 * x + 1.1 * y),
                     0.5 + 0.4 * np.sin(2.0 * y - 1.3 * x),
                     0.5 + 0.4 * np.cos(2.7 * np.sqrt(x * x + y * y))), axis=1)


def train(steps):
    rng = np.random.default_rng(0x565249)
    parameters = []
    for inputs, outputs in zip(WIDTHS[:-1], WIDTHS[1:]):
        parameters.extend((rng.normal(0, np.sqrt(2 / inputs), (inputs, outputs)).astype(np.float32),
                           np.zeros(outputs, np.float32)))
    momentum = [np.zeros_like(value) for value in parameters]
    variance = [np.zeros_like(value) for value in parameters]
    for step in range(1, steps + 1):
        points = rng.uniform(-1, 1, (1024, 2)).astype(np.float32)
        first = points @ parameters[0] + parameters[1]
        hidden1 = np.maximum(first, 0)
        second = hidden1 @ parameters[2] + parameters[3]
        hidden2 = np.maximum(second, 0)
        prediction = hidden2 @ parameters[4] + parameters[5]
        gradient = 2 * (prediction - reference(points)) / (points.shape[0] * 3)
        gradients = [None] * 6
        gradients[4] = hidden2.T @ gradient
        gradients[5] = gradient.sum(axis=0)
        gradient = (gradient @ parameters[4].T) * (second > 0)
        gradients[2] = hidden1.T @ gradient
        gradients[3] = gradient.sum(axis=0)
        gradient = (gradient @ parameters[2].T) * (first > 0)
        gradients[0] = points.T @ gradient
        gradients[1] = gradient.sum(axis=0)
        rate = 0.003 * (0.15 + 0.85 * (1 - step / steps))
        for index in range(6):
            momentum[index] = 0.9 * momentum[index] + 0.1 * gradients[index]
            variance[index] = 0.999 * variance[index] + 0.001 * gradients[index] ** 2
            corrected_mean = momentum[index] / (1 - 0.9 ** step)
            corrected_variance = variance[index] / (1 - 0.999 ** step)
            parameters[index] -= rate * corrected_mean / (np.sqrt(corrected_variance) + 1e-8)
        if step % 500 == 0:
            rmse = float(np.sqrt(np.mean((prediction - reference(points)) ** 2)))
            print(f"Step {step}: RMSE {rmse:.6f}")
    return parameters


def write_header(parameters, output):
    # Slang multiplies output-row matrices by column vectors. Preserve portable FP32 weights;
    # VRI converts them to the selected device's FP16 inference layout at startup.
    arrays = [value.T.reshape(-1) if value.ndim == 2 else value for value in parameters]
    offsets = np.cumsum([0] + [value.size for value in arrays[:-1]])
    data = np.concatenate(arrays)
    text = ["#pragma once", "// Generated by examples/mlp/train.py. No external model or dataset is used.",
            "#include <array>", "#include <cstdint>", "", "namespace vriex::mlp", "{",
            "    constexpr std::array<uint32_t, 4> kWidths {2, 32, 32, 3};",
            "    constexpr std::array<uint32_t, 6> kOffsets {" + ", ".join(map(str, offsets)) + "};",
            f"    constexpr std::array<float, {data.size}> kWeights {{"]
    for start in range(0, data.size, 6):
        values = [f"{float(value):.9e}f" for value in data[start:start + 6]]
        text.append("        " + ", ".join(values) + ",")
    text.extend(("    };", "} // namespace vriex::mlp", ""))
    output.write_text("\n".join(text))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--steps", type=int, default=3500)
    parser.add_argument("--output", type=Path, default=Path(__file__).with_name("model_weights.h"))
    arguments = parser.parse_args()
    if not 1 <= arguments.steps <= 100000:
        parser.error("steps must be between 1 and 100000")
    write_header(train(arguments.steps), arguments.output)


if __name__ == "__main__":
    main()
